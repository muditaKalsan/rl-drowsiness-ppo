"""
Generate all required plots for the drowsiness detection project.
The script expects the following files in `results/`:
- `metrics.csv` (generated by evaluate.py)
- `confusion_<METHOD>.npy` for each baseline (saved by baseline.py)
- `action_counts_pen<PENALTY>.npy` for each PPO penalty (saved by evaluate.py)
It produces PNG figures in the same folder.
"""

import os
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from pathlib import Path
from config import RESULTS_DIR, CHUNK_LENGTH_SECONDS

def _load_metrics():
    csv_path = RESULTS_DIR / "metrics.csv"
    return pd.read_csv(csv_path)

def plot_accuracy_vs_delay(metrics):
    plt.figure(figsize=(6,4))
    # PPO entries have avg_delay column filled
    ppo = metrics[metrics["method"].str.startswith("PPO")]
    plt.plot(ppo["avg_delay_s"], ppo["accuracy"], "o-", label="PPO (various penalties)")
    # Baselines: extract k from method name e.g. SVM_k2
    baselines = metrics[~metrics["method"].str.startswith("PPO")]
    for _, row in baselines.iterrows():
        if "_k" in row["method"]:
            k = int(row["method"].split("_k")[1])
            delay = k * CHUNK_LENGTH_SECONDS
            plt.scatter(delay, row["accuracy"], label=row["method"])
    plt.xlabel("Average detection delay (s)")
    plt.ylabel("Accuracy")
    plt.title("Accuracy vs detection delay")
    plt.grid(True)
    plt.legend()
    out = RESULTS_DIR / "accuracy_vs_delay.png"
    plt.savefig(out)
    plt.close()
    print(f"[INFO] Saved {out}")

def plot_training_reward():
    progress_path = RESULTS_DIR / "progress.csv"
    if not progress_path.exists():
        print("[WARN] No training progress file (progress.csv) found.")
        return
    prog = pd.read_csv(progress_path)
    plt.figure(figsize=(6,4))
    plt.plot(prog["timesteps"], prog["mean_reward"], label="Mean reward")
    plt.xlabel("Timesteps")
    plt.ylabel("Mean reward")
    plt.title("Training reward curve")
    plt.grid(True)
    out = RESULTS_DIR / "training_reward.png"
    plt.savefig(out)
    plt.close()
    print(f"[INFO] Saved {out}")

def plot_confusion_matrices():
    # Load each baseline confusion matrix saved as .npy
    for file in os.listdir(RESULTS_DIR):
        if file.startswith("confusion_") and file.endswith('.npy'):
            method = file[len("confusion_"):-len('.npy')]
            cm = np.load(RESULTS_DIR / file)
            plt.figure(figsize=(4,3))
            plt.imshow(cm, interpolation='nearest', cmap=plt.cm.Blues)
            plt.title(f"Confusion matrix: {method}")
            plt.colorbar()
            classes = ["Alert", "Drowsy"]
            tick_marks = np.arange(len(classes))
            plt.xticks(tick_marks, classes, rotation=45)
            plt.yticks(tick_marks, classes)
            thresh = cm.max() / 2.
            for i, j in np.ndindex(cm.shape):
                plt.text(j, i, format(cm[i, j], 'd'),
                         ha="center", va="center",
                         color="white" if cm[i, j] > thresh else "black")
            plt.ylabel('True label')
            plt.xlabel('Predicted label')
            out = RESULTS_DIR / f"confusion_{method}.png"
            plt.tight_layout()
            plt.savefig(out)
            plt.close()
            print(f"[INFO] Saved {out}")

def plot_action_distribution():
    # For each penalty, load action_counts (array length = n_chunks)
    files = [f for f in os.listdir(RESULTS_DIR) if f.startswith('action_counts_pen') and f.endswith('.npy')]
    if not files:
        print('[WARN] No action count files found.')
        return
    plt.figure(figsize=(8,4))
    for f in files:
        penalty = f[len('action_counts_pen'):-len('.npy')]
        counts = np.load(RESULTS_DIR / f)
        total = counts.sum()
        # normalize to fraction of total waits occurring at each chunk index
        fractions = counts / total if total > 0 else np.zeros_like(counts)
        plt.plot(np.arange(1, len(fractions)+1), fractions, marker='o', label=f"pen={penalty}")
    plt.xlabel('Chunk index (1 = first chunk)')
    plt.ylabel('Fraction of Wait actions')
    plt.title('How often the agent chooses Wait at each time step')
    plt.legend()
    plt.grid(True)
    out = RESULTS_DIR / 'wait_fraction.png'
    plt.savefig(out)
    plt.close()
    print(f"[INFO] Saved {out}")

def plot_bar_accuracy_f1(metrics):
    plt.figure(figsize=(8,4))
    methods = metrics["method"]
    acc = metrics["accuracy"]
    f1 = metrics["macro_f1"]
    ind = np.arange(len(methods))
    width = 0.35
    plt.bar(ind, acc, width, label='Accuracy')
    plt.bar(ind + width, f1, width, label='Macro F1')
    plt.xticks(ind + width/2, methods, rotation=45, ha='right')
    plt.ylabel('Score')
    plt.title('Accuracy and Macro F1 for all methods')
    plt.legend()
    plt.tight_layout()
    out = RESULTS_DIR / 'bar_accuracy_f1.png'
    plt.savefig(out)
    plt.close()
    print(f"[INFO] Saved {out}")

def main():
    metrics = _load_metrics()
    plot_accuracy_vs_delay(metrics)
    plot_training_reward()
    plot_confusion_matrices()
    plot_action_distribution()
    plot_bar_accuracy_f1(metrics)

if __name__ == '__main__':
    main()
